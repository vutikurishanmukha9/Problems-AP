/** Lookup MLA by constituency name */
export function getMLAForConstituency(constituencyName: string): string | undefined {
  const match = CONSTITUENCY_DATA.find(
    (c) => c.name.toLowerCase() === constituencyName.trim().toLowerCase(),
  );
  return match?.mla;
}

/** Lookup District for a given constituency name */
export function getDistrictForConstituency(constituencyName: string): string | undefined {
  const match = CONSTITUENCY_DATA.find(
    (c) => c.name.toLowerCase() === constituencyName.trim().toLowerCase(),
  );
  return match?.district;
}

/** Get all constituencies in a given district */
export function getConstituenciesByDistrict(districtName: string): ConstituencyInfo[] {
  const normalized = districtName.trim().toLowerCase();
  return CONSTITUENCY_DATA.filter((c) => c.district.toLowerCase() === normalized);
}
